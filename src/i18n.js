export function resolveLang(setting) {
    if (setting === 'en' || setting === 'ru') return setting;
    let st = '';
    try { st = localStorage.getItem('language') || ''; } catch { /* ignore */ }
    const l = (st || navigator.language || 'en').toLowerCase();
    return l.startsWith('ru') || l.startsWith('uk') || l.startsWith('be') ? 'ru' : 'en';
}

export function strings(lang) {
    return STRINGS[lang] || STRINGS.en;
}
